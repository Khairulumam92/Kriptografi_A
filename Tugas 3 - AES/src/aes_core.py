RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]


def _clone_state(state: State) -> State:
    return [row[:] for row in state]


def bytes_to_state(block: bytes) -> State:
    if len(block) != 16:
        raise ValueError("Block harus 16 byte untuk AES-128.")
    state = [[0 for _ in range(4)] for _ in range(4)]
    for column in range(4):
        for row in range(4):
            state[row][column] = block[(column * 4) + row]
    return state


def state_to_bytes(state: State) -> bytes:
    data = bytearray(16)
    for column in range(4):
        for row in range(4):
            data[(column * 4) + row] = state[row][column]
    return bytes(data)


def sub_bytes(state: State) -> State:
    return [[S_BOX[value] for value in row] for row in state]


def inv_sub_bytes(state: State) -> State:
    return [[INV_S_BOX[value] for value in row] for row in state]


def shift_rows(state: State) -> State:
    shifted = _clone_state(state)
    for row in range(1, 4):
        shifted[row] = state[row][row:] + state[row][:row]
    return shifted


def inv_shift_rows(state: State) -> State:
    shifted = _clone_state(state)
    for row in range(1, 4):
        shifted[row] = state[row][-row:] + state[row][:-row]
    return shifted


def gmul(a: int, b: int) -> int:
    result = 0
    value = a
    factor = b
    for _ in range(8):
        if factor & 1:
            result ^= value
        high_bit_set = value & 0x80
        value = (value << 1) & 0xFF
        if high_bit_set:
            value ^= 0x1B
        factor >>= 1
    return result


def mix_columns(state: State) -> State:
    mixed = [[0 for _ in range(4)] for _ in range(4)]
    for col in range(4):
        s0, s1, s2, s3 = (state[0][col], state[1][col], state[2][col], state[3][col])
        mixed[0][col] = gmul(s0, 0x02) ^ gmul(s1, 0x03) ^ s2 ^ s3
        mixed[1][col] = s0 ^ gmul(s1, 0x02) ^ gmul(s2, 0x03) ^ s3
        mixed[2][col] = s0 ^ s1 ^ gmul(s2, 0x02) ^ gmul(s3, 0x03)
        mixed[3][col] = gmul(s0, 0x03) ^ s1 ^ s2 ^ gmul(s3, 0x02)
    return mixed


def inv_mix_columns(state: State) -> State:
    mixed = [[0 for _ in range(4)] for _ in range(4)]
    for col in range(4):
        s0, s1, s2, s3 = (state[0][col], state[1][col], state[2][col], state[3][col])
        mixed[0][col] = gmul(s0, 0x0E) ^ gmul(s1, 0x0B) ^ gmul(s2, 0x0D) ^ gmul(s3, 0x09)
        mixed[1][col] = gmul(s0, 0x09) ^ gmul(s1, 0x0E) ^ gmul(s2, 0x0B) ^ gmul(s3, 0x0D)
        mixed[2][col] = gmul(s0, 0x0D) ^ gmul(s1, 0x09) ^ gmul(s2, 0x0E) ^ gmul(s3, 0x0B)
        mixed[3][col] = gmul(s0, 0x0B) ^ gmul(s1, 0x0D) ^ gmul(s2, 0x09) ^ gmul(s3, 0x0E)
    return mixed


def add_round_key(state: State, round_key: State) -> State:
    return [[state[row][col] ^ round_key[row][col] for col in range(4)] for row in range(4)]


def rot_word(word: List[int]) -> List[int]:
    return word[1:] + word[:1]


def sub_word(word: List[int]) -> List[int]:
    return [S_BOX[byte] for byte in word]


def key_expansion(key: bytes) -> List[State]:
    if len(key) != 16:
        raise ValueError("Key AES-128 harus 16 byte.")

    words: List[List[int]] = [[0, 0, 0, 0] for _ in range(44)]
    for index in range(4):
        words[index] = [key[(index * 4) + offset] for offset in range(4)]

    for index in range(4, 44):
        temp = words[index - 1][:]
        if index % 4 == 0:
            temp = sub_word(rot_word(temp))
            temp[0] ^= RCON[index // 4]
        words[index] = [words[index - 4][byte] ^ temp[byte] for byte in range(4)]

    round_keys: List[State] = []
    for round_index in range(11):
        state = [[0 for _ in range(4)] for _ in range(4)]
        for col in range(4):
            word = words[(round_index * 4) + col]
            for row in range(4):
                state[row][col] = word[row]
        round_keys.append(state)
    return round_keys


def aes_encrypt_block(block: bytes, key: bytes, collect_trace: bool = False) -> Tuple[bytes, List[Tuple[str, State]]]:
    state = bytes_to_state(block)
    round_keys = key_expansion(key)
    trace: List[Tuple[str, State]] = []

    if collect_trace:
        trace.append(("Initial State", _clone_state(state)))

    state = add_round_key(state, round_keys[0])
    if collect_trace:
        trace.append(("AddRoundKey (Round 0)", _clone_state(state)))

    for round_number in range(1, 10):
        state = sub_bytes(state)
        if collect_trace:
            trace.append((f"Round {round_number} - SubBytes", _clone_state(state)))

        state = shift_rows(state)
        if collect_trace:
            trace.append((f"Round {round_number} - ShiftRows", _clone_state(state)))

        state = mix_columns(state)
        if collect_trace:
            trace.append((f"Round {round_number} - MixColumns", _clone_state(state)))

        state = add_round_key(state, round_keys[round_number])
        if collect_trace:
            trace.append((f"Round {round_number} - AddRoundKey", _clone_state(state)))

    state = sub_bytes(state)
    if collect_trace:
        trace.append(("Round 10 - SubBytes", _clone_state(state)))

    state = shift_rows(state)
    if collect_trace:
        trace.append(("Round 10 - ShiftRows", _clone_state(state)))

    state = add_round_key(state, round_keys[10])
    if collect_trace:
        trace.append(("Round 10 - AddRoundKey", _clone_state(state)))
        trace.append(("Ciphertext State", _clone_state(state)))

    return state_to_bytes(state), trace


def aes_decrypt_block(block: bytes, key: bytes, collect_trace: bool = False) -> Tuple[bytes, List[Tuple[str, State]]]:
    state = bytes_to_state(block)
    round_keys = key_expansion(key)
    trace: List[Tuple[str, State]] = []

    if collect_trace:
        trace.append(("Initial Cipher State", _clone_state(state)))

    state = add_round_key(state, round_keys[10])
    if collect_trace:
        trace.append(("AddRoundKey (Round 10)", _clone_state(state)))

    for round_number in range(9, 0, -1):
        state = inv_shift_rows(state)
        if collect_trace:
            trace.append((f"Round {round_number} - InvShiftRows", _clone_state(state)))

        state = inv_sub_bytes(state)
        if collect_trace:
            trace.append((f"Round {round_number} - InvSubBytes", _clone_state(state)))

        state = add_round_key(state, round_keys[round_number])
        if collect_trace:
            trace.append((f"Round {round_number} - AddRoundKey", _clone_state(state)))

        state = inv_mix_columns(state)
        if collect_trace:
            trace.append((f"Round {round_number} - InvMixColumns", _clone_state(state)))

    state = inv_shift_rows(state)
    if collect_trace:
        trace.append(("Round 0 - InvShiftRows", _clone_state(state)))

    state = inv_sub_bytes(state)
    if collect_trace:
        trace.append(("Round 0 - InvSubBytes", _clone_state(state)))

    state = add_round_key(state, round_keys[0])
    if collect_trace:
        trace.append(("Round 0 - AddRoundKey", _clone_state(state)))
        trace.append(("Recovered Plaintext State", _clone_state(state)))

    return state_to_bytes(state), trace
